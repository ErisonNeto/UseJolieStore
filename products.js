window.JOLIE_PRODUCTS = JOLIE_FALLBACK_PRODUCTS;

const JOLIE_CATEGORY_LABELS = { conjuntos: "Conjuntos", tops: "Tops", regatas: "Regatas", vestidos: "Vestidos", shorts: "Shorts", saias: "Saias", calcas: "Calças", acessorios: "Acessórios", outros: "Outros" };

function mapSupabaseProduct(row) {
  const pattern = Array.isArray(row.patterns) && row.patterns.length ? row.patterns[0] : "";
  return {
    id: row.id,
    name: row.name,
    category: row.category || "outros",
    categoryLabel: JOLIE_CATEGORY_LABELS[row.category] || row.category || "Outros",
    variant: pattern,
    description: row.description || "",
    price: Number(row.price || 0),
    installments: Number(row.installments || 1),
    interestFree: row.interest_free !== false,
    badge: { text: row.badge || "", tone: row.badge_style || "pink" },
    launch: Boolean(row.is_launch),
    isNew: Boolean(row.is_new),
    featured: Boolean(row.featured),
    status: row.status === "sold_out" ? "soldout" : row.status === "hidden" ? "hidden" : "available",
    sizes: Array.isArray(row.sizes) ? row.sizes : [],
    colors: Array.isArray(row.colors) ? row.colors : [],
    variants: Array.isArray(row.variants) ? row.variants : [],
    image: row.image_url || "",
    imageAlt: `${row.name || "Produto"} da Use Jolie`,
    order: Number(row.sort_order || 0),
    createdAt: row.created_at || "",
    updatedAt: row.updated_at || ""
  };
}

async function loadJolieProducts() {
  try {
    if (!window.supabase || !window.JOLIE_SUPABASE) throw new Error("Supabase indisponível");
    const client = window.supabase.createClient(window.JOLIE_SUPABASE.url, window.JOLIE_SUPABASE.key);
    const { data, error } = await client
      .from("products")
      .select("*")
      .in("status", ["published", "sold_out"])
      .order("is_launch", { ascending: false })
      .order("sort_order", { ascending: true })
      .order("created_at", { ascending: false });
    if (error) throw error;
    window.JOLIE_PRODUCTS = (data || []).map(mapSupabaseProduct);
    window.dispatchEvent(new CustomEvent("jolie:products-loaded"));
  } catch (error) {
    console.warn("Use Jolie: usando catálogo local de fallback.", error);
    window.JOLIE_PRODUCTS = JOLIE_FALLBACK_PRODUCTS;
    window.dispatchEvent(new CustomEvent("jolie:products-loaded"));
  }
}

loadJolieProducts();
